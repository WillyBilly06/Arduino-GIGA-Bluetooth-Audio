"""Source-derived windows and synthetic AOSP encoder round trips; no hardware.

Fixtures are independently generated by the pinned upstream Rust encoder.
Requires clang/clang++ and Python's standard library; no Rust or NumPy needed.
"""
from pathlib import Path
import argparse,hashlib,json,math,os,shutil,struct,subprocess,time
ROOT=Path(__file__).resolve().parents[1]

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=ROOT/'build/lhdc-aosp-tests')
    p.add_argument('--cc');p.add_argument('--cxx');p.add_argument('--asan',action='store_true');p.add_argument('--sanitize',action='store_true')
    a=p.parse_args();out=a.output.resolve()
    if out==ROOT or any(ROOT/n==out or ROOT/n in out.parents for n in ('src','tests','tools','examples','docs')):p.error('output must be outside source directories')
    out.mkdir(parents=True,exist_ok=True)
    cc=a.cc or shutil.which('clang');cx=a.cxx or shutil.which('clang++');assert cc and cx
    env=os.environ.copy()
    if a.asan:
        rt=Path(subprocess.check_output([cc,'-print-runtime-dir'],text=True).strip())
        env['PATH']=str(rt)+os.pathsep+str(rt.parent/'windows')+os.pathsep+env.get('PATH','')
    flags=['-O2','-g','-fwrapv','-fno-strict-aliasing','-ffp-contract=off','-DGBR_HOST_TEST=1','-D_CRT_SECURE_NO_WARNINGS','-I'+str(ROOT/'src')]
    if a.asan:flags+=['-fsanitize=address','-fno-omit-frame-pointer']
    if a.sanitize:flags+=['-fsanitize=undefined','-fsanitize-trap=undefined','-fno-sanitize=shift,signed-integer-overflow']
    flags+=['-DGBR_ENABLE_'+n+'='+str(int(n=='LHDC'))for n in ('SBC','AAC','AAC_HE','APTX','LDAC','LHDC','OPUS','SSC')]
    fixture=ROOT/'tests/lhdc_aosp';manifest=json.loads((fixture/'manifest.json').read_text())
    sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    for n,pin in manifest['files'].items():
        f=fixture/n;assert f.stat().st_size==pin['bytes']and sha(f)==pin['sha256'],n
    # The same-TU wrapper includes the unmodified production decoder and adds
    # private descriptor/fast-versus-general checks, without production hooks.
    decoder_sources=[s for s in sorted((ROOT/'src/vendor/codecs/lhdc').glob('*.c'))if s.name!='lhdc_dec.c']
    sources=[ROOT/'tests/lhdc_window_private.c',*decoder_sources,ROOT/'src/codecs/Codecs.cpp',ROOT/'src/detail/Memory.cpp',ROOT/'src/detail/Decoder.cpp',ROOT/'tests/test_lhdc_aosp.cpp']
    rec=dict(status='RUNNING',scope=manifest['scope'],source_sha256={str(s.relative_to(ROOT)):sha(s)for s in sources},
        fixture_manifest_sha256=sha(fixture/'manifest.json'),asan=a.asan,ubsan=a.sanitize,
        ubsan_exclusions=['legacy shift','signed-integer-overflow']if a.sanitize else[],steps=[],results=[])
    rec['source_sha256']['src/vendor/codecs/lhdc/lhdc_dec.c']=sha(ROOT/'src/vendor/codecs/lhdc/lhdc_dec.c')
    def save():(out/'receipt.json').write_text(json.dumps(rec,indent=2)+'\n')
    def run(label,cmd):
        cmd=list(map(str,cmd));r=subprocess.run(cmd,cwd=ROOT,env=env,capture_output=True,text=True,timeout=90)
        (out/(label+'.stdout.log')).write_text(r.stdout);(out/(label+'.stderr.log')).write_text(r.stderr)
        rec['steps'].append(dict(label=label,command=cmd,returncode=r.returncode));save()
        assert r.returncode==0,(label,r.stderr[-2000:])
    started=time.monotonic();save()
    try:
        objects=[]
        for i,s in enumerate(sources):
            o=out/(str(i)+'.o');objects.append(o)
            run('compile-'+str(i),[cc if s.suffix=='.c'else cx,*flags,'-std=c11'if s.suffix=='.c'else'-std=c++17','-c',s,'-o',o])
        exe=out/('lhdc-aosp.exe'if os.name=='nt'else'lhdc-aosp')
        run('link',[cx,*flags,*objects,'-o',exe])
        run('windows',[exe,'--windows',out/'windows.f32'])
        expected=[]
        for n in (480,960,1920):
            ramp=[v/(1<<31)for v in struct.unpack('<'+'i'*(n//5),(fixture/f'window-{n//5}.q31').read_bytes())]
            z=(n//2-len(ramp))//2;expected.extend([0.0]*z+ramp+[1.0]*(2*z)+ramp[::-1]+[0.0]*z)
        expected=struct.pack('<'+'f'*len(expected),*expected)
        assert (out/'windows.f32').read_bytes()==expected,'production windows differ from pinned AOSP Q31 reference'
        rec['source_derived_window_values']=len(expected)//4
        for case in manifest['cases']:
            name=case['name'];pcm=out/(name+'.s32le');d=fixture/name
            run('decode-'+name,[exe,d/'encoded.bin',pcm,case['rate'],case['bits']])
            raw=(d/'input.pcm').read_bytes();bits=case['bits']
            if bits==16:x=struct.unpack('<'+'h'*(len(raw)//2),raw)
            else:x=[int.from_bytes(raw[i:i+3],'little',signed=True)for i in range(0,len(raw),3)]
            y=struct.unpack('<'+'i'*(pcm.stat().st_size//4),pcm.read_bytes());assert len(y)==len(x)
            h=240 if case['rate']<=48000 else case['rate']//200;lag=case['delay_samples'];scale=1<<(32-bits)
            gains=[];snrs=[]
            for ch in range(2):
                xx=x[8*h+ch:len(x)-2*lag:2];yy=y[8*h+2*lag+ch::2];assert len(xx)==len(yy)
                energy=sum((v*scale)**2 for v in xx);cross=sum(v*scale*w for v,w in zip(xx,yy));error=sum((v*scale-w)**2 for v,w in zip(xx,yy))
                gain=20*math.log10(cross/energy);snr=10*math.log10(energy/error)
                assert abs(gain)<=manifest['fidelity_limits']['maximum_abs_gain_db'],(name,ch,'level',gain)
                assert snr>=manifest['fidelity_limits']['minimum_snr_db'],(name,ch,'SNR',snr)
                gains.append(gain);snrs.append(snr)
            rec['results'].append(dict(name=name,frames=case['frames'],gain_db=gains,snr_db=snrs,output_sha256=sha(pcm)))
            print(name,'gain_db='+str(gains),'snr_db='+str(snrs),flush=True)
        assert all(sha(ROOT/n)==v for n,v in rec['source_sha256'].items())
        rec.update(status='PASS_SYNTHETIC_AOSP_ENCODER_REFERENCE',configurations=len(rec['results']),encoded_frames=sum(c['frames']for c in manifest['cases']),seconds=time.monotonic()-started)
    except BaseException:
        rec['status']='FAILED_REFERENCE_TEST';raise
    finally:save()
    print('PASS AOSP-derived 3360 window values and eight real encoder configurations; no physical qualification')

if __name__=='__main__':main()
